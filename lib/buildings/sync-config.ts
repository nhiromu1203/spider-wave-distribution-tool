/**
 * 取得元（OSM 等）からの建物登録を許可するかどうか。
 *
 * ── なぜ既定で止めているか ──────────────────────────────────
 * 以前は「そのエリアに取得元由来（source='data_source'）の建物が
 * 0 件なら自動で取得する」という作りだった。
 *
 * 建物マスタを CSV（source='import'）で作り直すと、取得元由来は
 * 常に 0 件のままになる。その結果、画面を開くたび・リロードするたびに
 * OSM から取得して登録され、736 件が 1,108 件へ増え続けた。
 *
 * 建物マスタの正は CSV。取得元からの登録は、必要なときだけ
 * BUILDING_AUTO_SYNC=1 を付けて明示的に有効にする。
 *
 * この判定はサーバーアクションからも画面からも使うため、
 * "use server" を付けたファイルには置かない（非 async 関数を
 * export できないため）。
 * ────────────────────────────────────────────────────────────
 */
export function isAreaSyncEnabled(): boolean {
  return process.env.BUILDING_AUTO_SYNC === "1";
}
